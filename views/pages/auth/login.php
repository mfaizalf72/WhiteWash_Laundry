<script>
(function() {
    // Show / Hide PIN Toggle
    var toggleBtn = document.getElementById('toggle-pin');
    var pinInput = document.getElementById('pin');
    var iconShow = document.getElementById('pin-icon-show');
    var iconHide = document.getElementById('pin-icon-hide');

    if (toggleBtn && pinInput) {
        toggleBtn.addEventListener('click', function() {
            var isPassword = pinInput.getAttribute('type') === 'password';
            if (isPassword) {
                pinInput.setAttribute('type', 'text');
                toggleBtn.setAttribute('aria-label', 'Hide PIN');
                if (iconShow) iconShow.classList.add('hidden');
                if (iconHide) iconHide.classList.remove('hidden');
            } else {
                pinInput.setAttribute('type', 'password');
                toggleBtn.setAttribute('aria-label', 'Show PIN');
                if (iconShow) iconShow.classList.remove('hidden');
                if (iconHide) iconHide.classList.add('hidden');
            }
            pinInput.focus();
        });
    }

    // Double-submit prevention & loading indicator
    var loginForm = document.getElementById('login-form');
    var submitBtn = document.getElementById('login-submit-btn');
    var submitText = document.getElementById('login-submit-text');
    var submitSpinner = document.getElementById('login-submit-spinner');

    if (loginForm && submitBtn) {
        loginForm.addEventListener('submit', function(e) {
            // Check native HTML5 form validity
            if (!loginForm.checkValidity()) {
                return; // Let browser display validation messages; do NOT disable
            }

            if (submitBtn.disabled) {
                e.preventDefault();
                return;
            }

            // Set loading state on submit
            submitBtn.disabled = true;
            submitBtn.classList.add('opacity-80', 'cursor-not-allowed');
            if (submitSpinner) submitSpinner.classList.remove('hidden');
            if (submitText) submitText.textContent = 'Signing in...';
        });

        // Reset button state on page navigation (e.g., browser back/forward cache)
        window.addEventListener('pageshow', function() {
            submitBtn.disabled = false;
            submitBtn.classList.remove('opacity-80', 'cursor-not-allowed');
            if (submitSpinner) submitSpinner.classList.add('hidden');
            if (submitText) submitText.textContent = 'Sign in securely';
        });
    }
})();
</script>
